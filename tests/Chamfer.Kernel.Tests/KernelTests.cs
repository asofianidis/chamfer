using Chamfer.Geometry;
using Chamfer.Kernel.Occt;

namespace Chamfer.Kernel.Tests;

public class KernelTests
{
    private const double Tol = 1e-6;

    private static Shape Rectangle(double w, double h, out int[] edgeMap) =>
        Modeling.Face(Plane3.Front,
        [
            [
                ProfileSegment.Line(0, 0, w, 0),
                ProfileSegment.Line(w, 0, w, h),
                ProfileSegment.Line(w, h, 0, h),
                ProfileSegment.Line(0, h, 0, 0),
            ],
        ], out edgeMap);

    [Fact]
    public void ReportsVersion() => Assert.Contains("OCCT", Shape.KernelVersion, StringComparison.Ordinal);

    [Fact]
    public void BoxHasExpectedTopologyAndVolume()
    {
        using var box = Modeling.Box(10, 20, 30);
        Assert.Equal(TopoKind.Solid, box.Kind);
        Assert.Equal(6, box.FaceCount);
        Assert.Equal(12, box.EdgeCount);
        Assert.Equal(8, box.VertexCount);
        Assert.True(box.IsValid);
        var m = box.MassProperties;
        Assert.Equal(6000, m.Volume, Tol);
        Assert.Equal(2 * ((10 * 20) + (20 * 30) + (10 * 30)), m.SurfaceArea, Tol);
        Assert.Equal(new Vec3(5, 10, 15), m.CenterOfMass);
        Assert.Equal(new Vec3(10, 20, 30), box.Bounds.Size);
    }

    [Fact]
    public void ProfileFaceMapsSegmentsToEdges()
    {
        using var face = Rectangle(40, 20, out var map);
        Assert.Equal(TopoKind.Face, face.Kind);
        Assert.Equal(4, face.EdgeCount);
        Assert.Equal(4, map.Distinct().Count());
        Assert.All(map, i => Assert.InRange(i, 1, 4));
        Assert.Equal(new Vec3(20, 0, 0), face.Edge(map[0]).Midpoint);
        var info = face.Face(1);
        Assert.Equal(SurfaceKind.Plane, info.Surface);
        Assert.Equal(800, info.Area, Tol);
        Assert.Equal(1, info.Normal.Z, Tol);
    }

    [Fact]
    public void FaceWithHoleHasReducedArea()
    {
        using var face = Modeling.Face(Plane3.Front,
        [
            [
                ProfileSegment.Line(0, 0, 50, 0),
                ProfileSegment.Line(50, 0, 50, 50),
                ProfileSegment.Line(50, 50, 0, 50),
                ProfileSegment.Line(0, 50, 0, 0),
            ],
            [ProfileSegment.Circle(25, 25, 10)],
        ]);
        Assert.Equal(2500 - (Math.PI * 100), face.Face(1).Area, 1e-6);
    }

    [Fact]
    public void ExtrudeTracksSideFacesAndCaps()
    {
        using var profile = Rectangle(40, 20, out var map);
        using var op = Modeling.Extrude(profile, new Vec3(0, 0, 10));
        using var solid = op.Result;
        Assert.Equal(6, solid.FaceCount);
        Assert.Equal(8000, solid.MassProperties.Volume, Tol);

        var bottom = Assert.Single(op.StartCaps);
        var top = Assert.Single(op.EndCaps);
        Assert.Equal(-1, solid.Face(bottom).Normal.Z, Tol);
        Assert.Equal(1, solid.Face(top).Normal.Z, Tol);

        // The side face generated by the bottom segment faces -Y.
        var side = Assert.Single(op.Generated(profile, TopoKind.Edge, map[0], TopoKind.Face));
        Assert.Equal(-1, solid.Face(side).Normal.Y, Tol);
    }

    [Fact]
    public void ArcProfileRevolvesIntoSolid()
    {
        // Half disc of radius 10 above the X axis, revolved about X: a sphere.
        using var face = Modeling.Face(Plane3.Front,
        [
            [
                ProfileSegment.Line(-10, 0, 10, 0),
                ProfileSegment.Arc(0, 0, 10, 0, -10, 0, ccw: true),
            ],
        ]);
        using var op = Modeling.Revolve(face, Vec3.Zero, Vec3.UnitX, 2 * Math.PI);
        using var solid = op.Result;
        Assert.Equal(4.0 / 3.0 * Math.PI * 1000, solid.MassProperties.Volume, 1e-3);
    }

    [Fact]
    public void BooleansAndHistory()
    {
        using var box = Modeling.Box(20, 20, 20);
        using var tool = Modeling.Cylinder(5, 40);
        using var moved = Modeling.Transform(tool, Transform3.Translation(new Vec3(10, 10, -10)));
        using var cylinder = moved.Result;
        using var cut = Modeling.Boolean(box, cylinder, BooleanKind.Cut);
        using var result = cut.Result;
        Assert.Equal(8000 - (Math.PI * 25 * 20), result.MassProperties.Volume, 1e-6);
        Assert.True(result.IsValid);

        // The box's top face (+Z) survives, modified by the hole.
        var top = Enumerable.Range(1, box.FaceCount).Single(i => box.Face(i).Normal.Z > 0.99);
        var after = box.Face(top).Area;
        var mapped = cut.Modified(box, TopoKind.Face, top, TopoKind.Face);
        Assert.NotNull(mapped);
        var f = Assert.Single(mapped);
        Assert.Equal(400 - (Math.PI * 25), result.Face(f).Area, 1e-6);
        Assert.Equal(400, after, Tol);
    }

    [Fact]
    public void FilletAndChamferRemoveMaterial()
    {
        using var box = Modeling.Box(20, 20, 20);
        var vertical = Enumerable.Range(1, box.EdgeCount)
            .Where(i => Math.Abs(box.Edge(i).CenterOrDirection.Z) > 0.99).ToArray();
        Assert.Equal(4, vertical.Length);

        using var fillet = Modeling.Fillet(box, vertical, [2, 2, 2, 2]);
        using var filleted = fillet.Result;
        var expected = 8000 - (4 * (4 - (Math.PI * 4 / 4)) * 20);
        Assert.Equal(expected, filleted.MassProperties.Volume, 1e-4);
        Assert.Equal(10, filleted.FaceCount);
        var generated = fillet.Generated(box, TopoKind.Edge, vertical[0], TopoKind.Face);
        var round = Assert.Single(generated);
        Assert.Equal(SurfaceKind.Cylinder, filleted.Face(round).Surface);
        Assert.Equal(2, filleted.Face(round).Radius, Tol);

        using var chamfer = Modeling.Chamfer(box, [vertical[0]], null, [3], [3]);
        using var chamfered = chamfer.Result;
        Assert.Equal(8000 - (4.5 * 20), chamfered.MassProperties.Volume, 1e-6);
    }

    [Fact]
    public void ShellHollowsSolid()
    {
        using var box = Modeling.Box(20, 20, 20);
        var top = Enumerable.Range(1, box.FaceCount).Single(i => box.Face(i).Normal.Z > 0.99);
        using var op = Modeling.Shell(box, [top], 2);
        using var shell = op.Result;
        Assert.Equal(8000 - (16 * 16 * 18), shell.MassProperties.Volume, 1e-4);
    }

    [Fact]
    public void TessellationCoversAllFaces()
    {
        using var cylinder = Modeling.Cylinder(10, 20);
        var mesh = cylinder.Tessellate(0.05, 0.3);
        Assert.True(mesh.TriangleCount > 20);
        Assert.Equal(cylinder.EdgeCount, mesh.EdgeCount);
        Assert.Equal(new[] { 1, 2, 3 }, mesh.TriangleFaces.Distinct().Order().ToArray());
        Assert.Equal(20, mesh.Bounds.Size.Z, 1e-6);

        // Normals point away from the axis on the side face.
        for (var t = 0; t < mesh.TriangleCount; t++)
        {
            var v = mesh.Triangles[3 * t];
            var p = mesh.Vertex(v);
            var n = new Vec3(mesh.Normals[3 * v], mesh.Normals[(3 * v) + 1], mesh.Normals[(3 * v) + 2]);
            if (Math.Abs(n.Z) < 0.1)
            {
                Assert.True(Vec3.Dot(n, new Vec3(p.X, p.Y, 0)) > 0);
            }
        }
    }

    [Fact]
    public void ExchangeFormatsRoundTrip()
    {
        var dir = Directory.CreateTempSubdirectory("chamfer-kernel-");
        try
        {
            using var box = Modeling.Box(10, 20, 30);
            var step = Path.Combine(dir.FullName, "box ü.step");
            box.WriteStep(step);
            using var fromStep = Shape.ReadStep(step);
            Assert.Equal(6000, fromStep.MassProperties.Volume, 1e-6);

            var iges = Path.Combine(dir.FullName, "box.igs");
            box.WriteIges(iges);
            using var fromIges = Shape.ReadIges(iges);
            Assert.Equal(6, fromIges.FaceCount);

            var stl = Path.Combine(dir.FullName, "box.stl");
            box.WriteStl(stl);
            Assert.True(new FileInfo(stl).Length > 84);

            using var fromBrep = Shape.FromBrep(box.ToBrep());
            Assert.Equal(6000, fromBrep.MassProperties.Volume, 1e-9);
        }
        finally
        {
            dir.Delete(recursive: true);
        }
    }

    [Fact]
    public void ErrorsSurfaceAsKernelExceptions()
    {
        using var box = Modeling.Box(10, 10, 10);
        var ex = Assert.Throws<KernelException>(() => box.Face(99));
        Assert.Contains("range", ex.Message, StringComparison.Ordinal);
        Assert.Throws<KernelException>(() => Modeling.Fillet(box, [1], [50]));
    }

    [Fact]
    public void MinimumDistanceBetweenShapes()
    {
        using var a = Modeling.Box(10, 10, 10);
        using var b0 = Modeling.Box(5, 5, 5);
        using var moved = Modeling.Transform(b0, Transform3.Translation(new Vec3(20, 0, 0)));
        using var b = moved.Result;
        var (d, p, q) = a.DistanceTo(b);
        Assert.Equal(10, d, 1e-9);
        Assert.Equal(10, p.X, 1e-9);
        Assert.Equal(20, q.X, 1e-9);
    }

    [Fact]
    public void SweepLoftAndHelix()
    {
        using var circle = Modeling.Face(Plane3.Front, [[ProfileSegment.Circle(0, 0, 2)]]);
        using var path = Modeling.Wire3D([Vec3.Zero, new Vec3(0, 0, 30)], spline: false, closed: false);
        using var sweep = Modeling.Sweep(circle, path);
        using var rod = sweep.Result;
        Assert.Equal(Math.PI * 4 * 30, rod.MassProperties.Volume, 1e-3);

        using var a = Modeling.Wire(Plane3.Front, [ProfileSegment.Circle(0, 0, 10)]);
        using var b = Modeling.Wire(Plane3.Front.Offset(10), [ProfileSegment.Circle(0, 0, 5)]);
        using var loft = Modeling.Loft([a, b]);
        using var frustum = loft.Result;
        Assert.Equal(Math.PI * 10 / 3 * (100 + 50 + 25), frustum.MassProperties.Volume, 1e-2);

        using var helix = Modeling.Helix(Plane3.Front, pitch: 5, height: 20, radius: 10);
        Assert.Equal(TopoKind.Wire, helix.Kind);
        var edge = helix.Edge(1);
        Assert.Equal(4 * Math.Sqrt(Math.Pow(2 * Math.PI * 10, 2) + 25), edge.Length, 1e-2);
    }
}
